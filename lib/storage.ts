import { v2 as cloudinary } from "cloudinary";
import crypto from "crypto";

export const ALLOWED_MIME_TYPES = new Set([
  "application/pdf",
  "image/jpeg",
  "image/jpg",
  "image/png",
]);

export const MAX_FILE_SIZE_BYTES = 10 * 1024 * 1024; // 10 MB

const ALLOWED_FORMATS = ["pdf", "jpg", "jpeg", "png"];
const FOLDER = "plannorium-people/identification";

// New uploads are "authenticated": they can't be fetched from a plain Cloudinary URL.
// "upload" (public) is still checked so documents uploaded before this change keep working.
const DELIVERY_TYPES = ["authenticated", "upload"] as const;
const RESOURCE_TYPES = ["image", "raw"] as const;

function isStorageConfigured(): boolean {
  return Boolean(
    process.env.CLOUDINARY_CLOUD_NAME &&
      process.env.CLOUDINARY_API_KEY &&
      process.env.CLOUDINARY_API_SECRET
  );
}

function configure(): void {
  cloudinary.config({
    cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
    api_key: process.env.CLOUDINARY_API_KEY,
    api_secret: process.env.CLOUDINARY_API_SECRET,
    secure: true,
  });
}

if (isStorageConfigured()) configure();

/**
 * Validate magic bytes for uploaded buffers.
 * PDF: %PDF (25 50 44 46)
 * JPEG: FF D8 FF
 * PNG: 89 50 4E 47 0D 0A 1A 0A
 */
export function validateMagicBytes(buffer: Buffer): { valid: boolean; detectedMime?: string } {
  if (buffer.length < 4) return { valid: false };

  // PDF
  if (
    buffer[0] === 0x25 &&
    buffer[1] === 0x50 &&
    buffer[2] === 0x44 &&
    buffer[3] === 0x46
  ) {
    return { valid: true, detectedMime: "application/pdf" };
  }

  // PNG
  if (
    buffer[0] === 0x89 &&
    buffer[1] === 0x50 &&
    buffer[2] === 0x4e &&
    buffer[3] === 0x47
  ) {
    return { valid: true, detectedMime: "image/png" };
  }

  // JPEG
  if (buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) {
    return { valid: true, detectedMime: "image/jpeg" };
  }

  return { valid: false };
}

/**
 * Generate a random UUID-based document key (no employee name or personal data in key).
 */
export function generateObjectKey(prefix = "documents"): string {
  const uuid = crypto.randomUUID();
  return `${prefix}/${uuid}`;
}

/**
 * Accepts only identification keys generated by this application.
 */
const DOCUMENT_KEY_PATTERN = /^identification\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

export function isDocumentKey(key: string): boolean {
  return DOCUMENT_KEY_PATTERN.test(key);
}

function publicIdFor(key: string): string {
  return `${FOLDER}/${key.replace(/^identification\//, "")}`;
}

interface StoredDocument {
  resourceType: (typeof RESOURCE_TYPES)[number];
  type: (typeof DELIVERY_TYPES)[number];
  format: string;
  bytes: number;
}

/** Finds a stored document, whichever delivery and resource type it was saved under. */
async function locateDocument(key: string): Promise<StoredDocument | null> {
  const publicId = publicIdFor(key);
  for (const type of DELIVERY_TYPES) {
    for (const resourceType of RESOURCE_TYPES) {
      try {
        const res = await cloudinary.api.resource(publicId, { resource_type: resourceType, type });
        return {
          resourceType,
          type,
          format: String(res?.format || "").toLowerCase(),
          bytes: Number(res?.bytes || 0),
        };
      } catch {
        // Not stored under this combination; try the next one
      }
    }
  }
  return null;
}

export interface PresignedUploadResult {
  uploadUrl: string;
  key: string;
  fields: Record<string, string | number>;
}

/**
 * Generate signed upload parameters for Cloudinary direct upload.
 */
export async function getPresignedUploadUrl(
  key: string,
  contentType: string
): Promise<PresignedUploadResult> {
  if (!ALLOWED_MIME_TYPES.has(contentType.toLowerCase())) {
    throw new Error("Unsupported file type. Only PDF, JPG, and PNG are accepted.");
  }
  if (!isStorageConfigured()) {
    throw new Error("Document storage is not configured. Please contact HR.");
  }

  const timestamp = Math.floor(Date.now() / 1000);
  // Every parameter here is covered by the signature, so the browser can't change
  // the folder, file name, privacy type or accepted formats.
  const paramsToSign: Record<string, string | number> = {
    allowed_formats: ALLOWED_FORMATS.join(","),
    folder: FOLDER,
    public_id: key.replace(/^identification\//, ""),
    timestamp,
    type: "authenticated",
  };

  const signature = cloudinary.utils.api_sign_request(
    paramsToSign,
    process.env.CLOUDINARY_API_SECRET as string
  );

  return {
    uploadUrl: `https://api.cloudinary.com/v1_1/${process.env.CLOUDINARY_CLOUD_NAME}/auto/upload`,
    key,
    fields: {
      ...paramsToSign,
      api_key: process.env.CLOUDINARY_API_KEY as string,
      signature,
    },
  };
}

/**
 * Generate a signed download URL that stops working after 5 minutes.
 */
export async function getPresignedDownloadUrl(key: string): Promise<string> {
  if (!isDocumentKey(key)) throw new Error("Invalid document reference.");
  if (!isStorageConfigured()) {
    throw new Error("Document storage is not configured.");
  }
  configure();

  const doc = await locateDocument(key);
  if (!doc) throw new Error("Document file not found in storage.");

  return cloudinary.utils.private_download_url(publicIdFor(key), doc.format, {
    resource_type: doc.resourceType,
    type: doc.type,
    expires_at: Math.floor(Date.now() / 1000) + 300,
  });
}

/**
 * Checks an uploaded object on Cloudinary: it must exist, be <= 10 MB and be a PDF/JPG/PNG.
 * Invalid objects are deleted.
 */
export async function verifyUploadedDocument(key: string): Promise<void> {
  if (!isDocumentKey(key)) throw new Error("Invalid document reference.");

  if (!isStorageConfigured()) {
    if (process.env.NODE_ENV === "production") {
      throw new Error("Document storage is not configured. Please contact HR.");
    }
    // Local development without storage credentials
    return;
  }

  const doc = await locateDocument(key);
  if (!doc) throw new Error("Uploaded document not found. Please upload it again.");

  if (doc.bytes === 0 || doc.bytes > MAX_FILE_SIZE_BYTES) {
    await deleteDocument(key);
    throw new Error("Document must be between 1 byte and 10 MB.");
  }

  if (doc.format && !ALLOWED_FORMATS.includes(doc.format)) {
    await deleteDocument(key);
    throw new Error("Document must be a PDF, JPG or PNG file.");
  }
}

/**
 * Permanently delete a document from Cloudinary storage.
 */
export async function deleteDocument(key: string): Promise<void> {
  if (!isStorageConfigured()) return;

  const publicId = publicIdFor(key);
  for (const type of DELIVERY_TYPES) {
    for (const resourceType of RESOURCE_TYPES) {
      try {
        // destroy resolves with { result: "not found" } instead of throwing
        const res = await cloudinary.uploader.destroy(publicId, {
          resource_type: resourceType,
          type,
          invalidate: true,
        });
        if (res?.result === "ok") return;
      } catch {
        // Try the next combination
      }
    }
  }
}
